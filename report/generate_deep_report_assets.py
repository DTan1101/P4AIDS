"""Generate self-contained LaTeX tables and vector PDFs from the five-model snapshot.

Run from the repository root: python report/generate_deep_report_assets.py
"""

import argparse
import hashlib
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "report"
MODELS = ["gru_fill", "gru_mask_delta", "gru_d", "brits", "saits"]
NAMES = {"gru_fill": "GRU-Fill", "gru_mask_delta": r"GRU+mask/$\Delta t$",
         "gru_d": "GRU-D", "brits": "BRITS", "saits": "SAITS"}
CASES = [("point", 0), *[(kind, rate) for kind in ("point", "subsequence", "block")
                           for rate in (.1, .3, .5)]]


def mean_std(row, metric="macro_f1"):
    return rf"${row[metric + '_mean']:.4f}\pm{row[metric + '_std']:.4f}$"


def case_name(kind, rate):
    return "Không ẩn thêm" if rate == 0 else rf"{kind.capitalize()} {rate:.0%}".replace("%", r"\%")


def table(name, caption, label, headers, rows, note="", font=r"\small"):
    lines = ["% Generated by report/generate_deep_report_assets.py; do not edit numeric cells.",
             r"\begin{table}[htbp]", r"\centering", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
             r"\begingroup", font, r"\setlength{\tabcolsep}{4pt}", r"\renewcommand{\arraystretch}{1.15}",
             r"\begin{tabular}{@{}l" + "c" * (len(headers) - 1) + r"@{}}", r"\toprule",
             " & ".join(headers) + r" \\", r"\midrule"]
    lines += [" & ".join(map(str, row)) + r" \\" for row in rows]
    lines += [r"\bottomrule", r"\end{tabular}", r"\endgroup"]
    if note:
        lines += [r"\par\smallskip", r"\begin{minipage}{\linewidth}\footnotesize " + note + r"\end{minipage}"]
    lines += [r"\end{table}", ""]
    (REPORT / "generated" / name).write_text("\n".join(lines), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--analysis-dir", type=Path, default=ROOT / "outputs/analysis/deep_report_5models")
    args = parser.parse_args()
    source = args.analysis_dir.resolve()
    data = pd.read_csv(source / "summary_mean_std.csv")
    raw = pd.read_csv(source / "runs.csv")
    overall = pd.read_csv(source / "overall_comparison.csv").set_index("model")
    cost = pd.read_csv(source / "cost_and_progress.csv").set_index("model")
    parameters = pd.read_csv(source / "model_parameters.csv").set_index("model")
    param_names = {"gru_fill": "GRU-Fill", "gru_mask_delta": "GRU+mask/delta",
                   "gru_d": "GRU-D", "brits": "BRITS", "saits": "SAITS"}
    snapshot = json.loads((source / "snapshot.json").read_text())
    manifest = json.loads((source / "sources/manifest.json").read_text())
    assert snapshot["verified_prediction_archives"] == 150
    assert set(data.model) == set(MODELS) and len(data) == 100 and len(raw) == 300
    assert (data.n_seeds == 3).all()
    for model in MODELS:
        assert len(raw[(raw.model == model) & (raw.split == "test")]) == 30
        assert next(j for j in manifest["jobs"] if j["model"] == model)["status"] == "complete"
    assert np.isfinite(data.filter(regex="_mean$|_std$").to_numpy()).all()
    # Check the less obvious aggregation: average cases within seed, then std across seeds.
    for model in MODELS:
        values = raw[(raw.model == model) & (raw.split == "test") & (raw.rate > 0)].groupby("seed").macro_f1.mean()
        assert np.isclose(values.mean(), overall.loc[model, "macro_f1_mean"])
        assert np.isclose(values.std(ddof=1), overall.loc[model, "macro_f1_std"])
    test = data[data.split == "test"].set_index(["model", "kind", "rate"])
    (REPORT / "generated").mkdir(exist_ok=True)
    (REPORT / "figs").mkdir(exist_ok=True)
    prepared = ROOT / "outputs/data/windows.npz"
    with np.load(prepared, allow_pickle=False) as archive:
        splits = []
        for name, years in (("train", "2006--2013"), ("val", "2014"), ("test", "2015--2016")):
            values = archive["y"][archive[f"{name}_idx"]]
            counts = np.bincount(values, minlength=2)
            splits.append([{"train": "Train", "val": "Validation", "test": "Test"}[name], years,
                           len(values), counts[0], counts[1], rf"{100*counts[1]/len(values):.2f}\%"])
    table("deep_split.tex", "Số cửa sổ và phân bố nhãn theo tập chia thời gian.", "tab:dl-split",
          ["Tập", "Năm nhãn", "Cửa sổ", "Rain", "Snow", "Tỷ lệ Snow"], splits)

    table("deep_no_extra.tex", "Kết quả test khi không giả lập thiếu bổ sung, trung bình và độ lệch chuẩn giữa ba seed.",
          "tab:ket-qua-day-du", ["Mô hình", "Macro F1", "PR-AUC", "Precision Snow", "Recall Snow"],
          [[NAMES[m], *[mean_std(test.loc[(m, "point", 0)], metric)
                       for metric in ("macro_f1", "pr_auc", "snow_precision", "snow_recall")]] for m in MODELS],
          r"Dữ liệu vẫn giữ phần thiếu tự nhiên; PR-AUC được tính bằng average precision cho Snow.", font=r"\footnotesize")
    for metric, title in (("macro_f1", "Macro F1"), ("pr_auc", "PR-AUC")):
        table(f"deep_{metric}.tex", f"{title} trên test theo điều kiện thiếu dữ liệu; mean $\\pm$ sample std giữa ba seed.",
              f"tab:dl-{metric.replace('_', '-')}", ["Điều kiện", *[NAMES[m] for m in MODELS]],
              [[case_name(k, r), *[mean_std(test.loc[(m, k, r)], metric) for m in MODELS]] for k, r in CASES],
              font=r"\scriptsize")
    table("deep_overall.tex", "Tổng hợp trên chín điều kiện thiếu, không gồm điều kiện không ẩn thêm.",
          "tab:dl-overall", ["Mô hình", "Macro F1", "PR-AUC", "Balanced accuracy"],
          [[NAMES[m], *[mean_std(overall.loc[m], key) for key in ("macro_f1", "pr_auc", "balanced_accuracy")]] for m in MODELS],
          r"Với mỗi seed, lấy trung bình không trọng số giữa chín case; sau đó tính mean và sample std giữa ba seed. Không dùng std giữa các case.",
          font=r"\footnotesize")
    paired = pd.read_csv(source / "paired_seed_differences.csv")
    paired = paired[(paired["split"] == "test") & (paired.contrast == "gru_mask_delta minus gru_fill")]
    delta = paired.groupby(["kind", "rate"]).macro_f1.agg(["mean", "std"])
    table("deep_ablation.tex", r"Ablation bổ sung mask/$\Delta t$ vào GRU, trên chín điều kiện thiếu.",
          "tab:dl-ablation", ["Điều kiện", "GRU-Fill", r"GRU+mask/$\Delta t$", r"Chênh lệch $F1$"],
          [[case_name(k, r), f"{test.loc[('gru_fill', k, r), 'macro_f1_mean']:.4f}",
            f"{test.loc[('gru_mask_delta', k, r), 'macro_f1_mean']:.4f}",
            rf"${delta.loc[(k,r), 'mean']:+.4f}\pm{delta.loc[(k,r), 'std']:.4f}$"] for k, r in CASES[1:]],
          r"Hai cột mô hình là mean giữa seed. Chênh lệch được ghép theo cùng case/seed rồi tính mean và sample std; dấu dương có lợi cho GRU+mask/$\Delta t$.",
          font=r"\footnotesize")
    table("deep_snow_subsequence50.tex", r"Precision, recall và F1 của Snow tại subsequence 50\%.",
          "tab:dl-snow-subsequence50", ["Mô hình", "Precision Snow", "Recall Snow", "F1 Snow"],
          [[NAMES[m], *[mean_std(test.loc[(m, "subsequence", .5)], key)
                       for key in ("snow_precision", "snow_recall", "snow_f1")]] for m in MODELS], font=r"\footnotesize")
    table("deep_cost.tex", "Chi phí pipeline và kích thước của năm mô hình, mỗi mô hình đủ 30 lượt.",
          "tab:chi-phi-tinh-toan", ["Mô hình", "Pipeline (phút)", "Epoch (giây)", "Tổng epoch", "Tham số"],
          [[NAMES[m], f"{cost.loc[m, 'pipeline_seconds']/60:.2f}",
            f"{cost.loc[m, 'epoch_interval_median_seconds']:.0f}",
            int(cost.loc[m, "epochs_completed_runs"]),
            f"{int(parameters.loc[param_names[m], 'total_parameters']):,}".replace(",", r"\,")] for m in MODELS],
          r"Pipeline gồm tiền xử lý, train, validation/test và lưu artifact, đo bằng \texttt{perf\_counter}. Cột epoch là trung vị khoảng timestamp giữa hai epoch liên tiếp, gồm train và validation, không phải thời gian GPU thuần. Tham số không gồm buffer cố định.",
          font=r"\footnotesize")
    table("deep_hyperparameters.tex", "Cấu hình cố định của chiến dịch Deep Learning, chưa thực hiện tìm kiếm siêu tham số.",
          "tab:dl-hyperparameters", ["Thiết lập", "Giá trị"],
          [["Cửa sổ / số biến / số lớp", "24 giờ / 5 / 2"], [r"Hidden size / SAITS d\_model", "64 / 64"],
           [r"SAITS: lớp mỗi khối / head / d\_ffn", "2 / 4 / 128"], ["Optimizer / learning rate", "Adam / 0.001"],
           ["Batch size / epoch tối đa", "64 / 50"], ["Early stopping / metric", "patience 10 / validation Macro F1"],
           ["Scheduler", "ReduceLROnPlateau, factor 0.5, patience 3"], ["Seed mô hình / mask", "42, 1, 2 / 123"],
           ["Deterministic", "Bật"]], font=r"\footnotesize")
    seeds = [42, 1, 2]
    seed_sections = []
    for model in MODELS:
        values = raw[(raw.model == model) & (raw.split == "test")].set_index(["kind", "rate", "seed"])
        name = f"deep_seeds_{model}.tex"
        table(name, f"Macro F1 test theo từng seed của {NAMES[model]}.", "tab:dl-seeds-" + model.replace("_", "-"),
              ["Điều kiện", *[f"Seed {seed}" for seed in seeds], r"Mean $\pm$ std"],
              [[case_name(k, r), *[f"{values.loc[(k, r, seed), 'macro_f1']:.4f}" for seed in seeds],
                mean_std(test.loc[(model, k, r)])] for k, r in CASES], font=r"\footnotesize")
        seed_sections.append(rf"\input{{generated/{name}}}")
    (REPORT / "generated/deep_seed_details.tex").write_text("\n".join(seed_sections) + "\n")

    plt.rcParams.update({"font.family": "DejaVu Serif", "font.size": 8, "pdf.fonttype": 42})
    colors = dict(zip(MODELS, plt.rcParams["axes.prop_cycle"].by_key()["color"]))
    for metric, title in (("macro_f1", "Macro F1"), ("pr_auc", "PR-AUC (Snow)")):
        fig, axes = plt.subplots(1, 3, figsize=(6.6, 3.0), sharey=True)
        for ax, kind, heading in zip(axes, ("point", "subsequence", "block"), ("Thiếu điểm", "Thiếu đoạn", "Thiếu khối")):
            for model in MODELS:
                points = [test.loc[(model, "point", 0)], *[test.loc[(model, kind, rate)] for rate in (.1, .3, .5)]]
                y = np.array([row[metric + "_mean"] for row in points])
                sd = np.array([row[metric + "_std"] for row in points])
                ax.plot([0, 10, 30, 50], y, marker="o", markersize=3, linewidth=1.2, color=colors[model], label=NAMES[model])
                ax.fill_between([0, 10, 30, 50], y-sd, y+sd, color=colors[model], alpha=.10)
            ax.set(title=heading, xlabel="Tỷ lệ thiếu mục tiêu (%)", xticks=[0, 10, 30, 50])
            ax.tick_params(labelsize=7)
            ax.grid(alpha=.25)
        axes[0].set_ylabel(title)
        fig.legend(*axes[0].get_legend_handles_labels(), loc="lower center", ncol=3, frameon=False, fontsize=8)
        fig.tight_layout(rect=[0, .22, 1, 1], pad=.6, w_pad=.3)
        fig.savefig(REPORT / "figs" / f"deep_{metric}_missingness.pdf")
        plt.close(fig)
    matrix = np.array([[test.loc[(m, k, r), "macro_f1_mean"] for m in MODELS] for k, r in CASES])
    fig, ax = plt.subplots(figsize=(6.6, 4.3))
    image = ax.imshow(matrix, aspect="auto", cmap="YlGnBu", vmin=.83, vmax=.95)
    ax.set_xticks(range(5), [NAMES[m] for m in MODELS], fontsize=8)
    ax.set_yticks(range(10), [case_name(k, r).replace(r"\%", "%") for k, r in CASES], fontsize=8)
    for i in range(10):
        for j in range(5):
            ax.text(j, i, f"{matrix[i,j]:.4f}", ha="center", va="center", fontsize=8,
                    color="white" if matrix[i,j] > .91 else "black", weight="bold" if j == matrix[i].argmax() else "normal")
    fig.colorbar(image, ax=ax, label="Macro F1 test (mean giữa 3 seed)")
    fig.tight_layout(pad=.6)
    fig.savefig(REPORT / "figs/deep_macro_f1_heatmap.pdf")
    plt.close(fig)
    fig, ax = plt.subplots(figsize=(6.6, 3.5))
    for model in MODELS:
        row = overall.loc[model]
        x = cost.loc[model, "pipeline_seconds"] / 60
        ax.errorbar(x, row.macro_f1_mean, yerr=row.macro_f1_std, fmt="o", capsize=3, color=colors[model])
        ax.annotate(NAMES[model], (x, row.macro_f1_mean), xytext=(5, 5), textcoords="offset points")
    ax.set(xscale="log", xlim=(12, 2000), xlabel="Thời gian pipeline cho 30 lượt (phút, thang log)",
           ylabel="Macro F1 trung bình trên 9 case thiếu")
    ax.grid(alpha=.25)
    fig.tight_layout(pad=.7)
    fig.savefig(REPORT / "figs/deep_performance_cost.pdf")
    plt.close(fig)
    files = ["summary_mean_std.csv", "runs.csv", "overall_comparison.csv", "cost_and_progress.csv",
             "model_parameters.csv", "paired_seed_differences.csv", "snapshot.json", "sources/manifest.json"]
    provenance = {"analysis_directory": str(source.relative_to(ROOT)) if source.is_relative_to(ROOT) else str(source),
                  "snapshot_time": snapshot["snapshot_time"], "selected_models": MODELS,
                  "verified_runs": 150, "sha256": {name: hashlib.sha256((source/name).read_bytes()).hexdigest() for name in files}}
    (REPORT / "generated/deep_sources.json").write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + "\n")
    print("Generated 4 vector PDFs and 15 LaTeX table/input files from 150 verified runs.")


if __name__ == "__main__":
    main()
